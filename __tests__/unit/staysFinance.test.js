const prisma = require('../../src/core/services/prismaClient');
const finance = require('../../src/brands/ghana/staysFinanceController');

function makeRes() {
  return { status: jest.fn().mockReturnThis(), json: jest.fn().mockReturnThis() };
}

function requestRow(overrides = {}) {
  return {
    id: 'pr-1',
    requestNumber: 'SPR-2026-ABCD1234',
    amount: 306,
    currency: 'GHS',
    bookingCount: 1,
    status: 'PROCESSING',
    cycleLabel: 'Twice a month',
    reference: null,
    notes: null,
    autoGenerated: false,
    payoutMethod: null,
    createdAt: new Date('2026-10-26T12:00:00.000Z'),
    updatedAt: new Date('2026-10-26T12:00:00.000Z'),
    ...overrides,
  };
}

describe('staysFinanceController', () => {
  let req;
  let res;
  let next;

  beforeEach(() => {
    jest.clearAllMocks();
    req = { supplierId: 'sup-1', user: { id: 'user-1' }, body: {}, query: {}, params: {} };
    res = makeRes();
    next = jest.fn();
    prisma.supplierProfile.findUnique.mockResolvedValue({
      payoutCycle: 'TWICE_MONTHLY',
      payoutCycleEffectiveAt: null,
      payoutCyclePending: null,
      payoutCyclePendingAt: null,
    });
    prisma.payoutMethod.count.mockResolvedValue(1);
    prisma.systemConfig.findUnique.mockResolvedValue(null);
  });

  it('summarises available, pending, in-review and paid balances', async () => {
    prisma.stayBooking.findMany.mockResolvedValue([
      { status: 'COMPLETED', payoutStatus: 'ELIGIBLE', supplierPayout: 306, amount: 360, currency: 'GHS' },
      { status: 'CONFIRMED', payoutStatus: 'PENDING', supplierPayout: 200, amount: 235, currency: 'GHS' },
      { status: 'COMPLETED', payoutStatus: 'PAID', supplierPayout: 100, amount: 118, currency: 'GHS' },
    ]);
    prisma.stayPayoutRequest.findMany.mockResolvedValue([{ amount: 150, currency: 'GHS' }]);

    await finance.getSummary(req, res, next);

    expect(next).not.toHaveBeenCalled();
    expect(res.json).toHaveBeenCalledWith({
      status: 'success',
      data: expect.objectContaining({
        availableBalance: { amount: 306, bookingCount: 1 },
        pendingClearance: expect.objectContaining({ amount: 200, bookingCount: 1 }),
        inReview: expect.objectContaining({ total: 150, count: 1 }),
        paidOut: { total: 100, count: 1 },
        currency: 'GHS',
      }),
    });
  });

  it('creates a payout request from completed eligible bookings', async () => {
    prisma.stayBooking.findMany.mockResolvedValue([
      { id: 'sb-1', amount: 360, platformCommission: 54, supplierPayout: 306, currency: 'GHS' },
    ]);
    prisma.stayPayoutRequest.create.mockResolvedValue(requestRow());

    await finance.createPayoutRequest(req, res, next);

    expect(next).not.toHaveBeenCalled();
    expect(prisma.stayPayoutRequest.create).toHaveBeenCalledWith(expect.objectContaining({
      data: expect.objectContaining({
        supplierId: 'sup-1',
        amount: 306,
        currency: 'GHS',
        bookingCount: 1,
      }),
    }));
    expect(prisma.stayPayoutRequestItem.createMany).toHaveBeenCalledWith({
      data: [expect.objectContaining({
        stayBookingId: 'sb-1',
        supplierPayout: 306,
      })],
    });
    expect(prisma.stayBooking.updateMany).toHaveBeenCalledWith({
      where: { id: { in: ['sb-1'] } },
      data: { payoutStatus: 'REQUESTED' },
    });
    expect(res.status).toHaveBeenCalledWith(201);
  });

  it('refuses a payout request when nothing is eligible', async () => {
    prisma.stayBooking.findMany.mockResolvedValue([]);

    await finance.createPayoutRequest(req, res, next);

    expect(next.mock.calls[0][0].statusCode).toBe(400);
    expect(prisma.stayPayoutRequest.create).not.toHaveBeenCalled();
  });

  it('cancels a request and releases its bookings', async () => {
    prisma.stayPayoutRequest.findFirst.mockResolvedValue({
      ...requestRow(),
      items: [{ stayBookingId: 'sb-1' }],
    });

    req.params = { id: 'pr-1' };
    await finance.cancelPayoutRequest(req, res, next);

    expect(next).not.toHaveBeenCalled();
    expect(prisma.stayPayoutRequest.update).toHaveBeenCalledWith({
      where: { id: 'pr-1' },
      data: { status: 'CANCELLED' },
    });
    expect(prisma.stayBooking.updateMany).toHaveBeenCalledWith({
      where: { id: { in: ['sb-1'] } },
      data: { payoutStatus: 'ELIGIBLE' },
    });
  });

  it('returns an empty charges ledger when there are no charges', async () => {
    prisma.staySupplierCharge.findMany.mockResolvedValue([]);

    await finance.getCharges(req, res, next);

    expect(next).not.toHaveBeenCalled();
    expect(res.json).toHaveBeenCalledWith({
      status: 'success',
      data: { charges: [], openTotals: [] },
    });
  });

  it('accepts the dashboard bookingId alias when filing a refund', async () => {
    prisma.stayBooking.findFirst.mockResolvedValue({ id: 'sb-1', amount: 360, currency: 'GHS' });
    prisma.stayDispute.create.mockResolvedValue({
      id: 'dsp-1',
      disputeNumber: 'SDS-2026-ABCD',
      reason: 'OTHER',
      description: 'Test',
      status: 'OPEN',
      resolution: null,
      refundAmount: 360,
      createdAt: new Date(),
      resolvedAt: null,
      stayBooking: {
        bookingNumber: 'TRG-S-1',
        checkIn: new Date('2026-11-10T00:00:00.000Z'),
        amount: 360,
        currency: 'GHS',
        property: { name: 'Akwaaba Coast Hotel' },
      },
    });

    req.body = { bookingId: 'sb-1', reason: 'OTHER', description: 'Test' };
    await finance.createDispute(req, res, next);

    expect(next).not.toHaveBeenCalled();
    expect(prisma.stayDispute.create).toHaveBeenCalledWith(expect.objectContaining({
      data: expect.objectContaining({ stayBookingId: 'sb-1', openedById: 'user-1' }),
    }));
    expect(res.status).toHaveBeenCalledWith(201);
  });
});
