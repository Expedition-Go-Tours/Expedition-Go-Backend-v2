  const prisma = {
    stayBooking: {
      findMany: jest.fn(),
      count: jest.fn(),
      updateMany: jest.fn(),
      findFirst: jest.fn(),
    },
    stayPayoutRequest: {
      findMany: jest.fn(),
      findFirst: jest.fn(),
      count: jest.fn(),
      create: jest.fn(),
      update: jest.fn(),
    },
    stayPayoutRequestItem: { createMany: jest.fn() },
    staySupplierCharge: { findMany: jest.fn() },
    stayDispute: {
      findMany: jest.fn(),
      findFirst: jest.fn(),
      count: jest.fn(),
      create: jest.fn(),
      update: jest.fn(),
    },
    stayRefundClaim: {
      findMany: jest.fn(),
      findFirst: jest.fn(),
      update: jest.fn(),
    },
    payoutMethod: { findFirst: jest.fn(), count: jest.fn() },
    supplierProfile: { findUnique: jest.fn() },
    systemConfig: { findUnique: jest.fn() },
    $transaction: jest.fn(),
  };
  prisma.$transaction.mockImplementation((arg) => (
    typeof arg === 'function' ? arg(prisma) : Promise.all(arg)
  ));
  return prisma;
